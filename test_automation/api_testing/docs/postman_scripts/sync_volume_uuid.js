/**
 * ==========================================================
 * 功能：同步卷 UUID 到模块变量
 * ==========================================================
 *
 * 【脚本目的】
 * 获取当前系统所有卷(UUID)，自动生成模块变量：
 *
 *      lv0_uuid
 *      lv1_uuid
 *      lv2_uuid
 *      ...
 *
 * 后续接口可直接使用：
 *
 *      lv0_uuid
 *      lv1_uuid
 *      lv2_uuid
 *
 * ==========================================================
 * 为什么每次都要同步？
 * ==========================================================
 *
 * 卷是动态变化的，例如：
 *
 * 第一次：
 *      lv0
 *      lv1
 *      lv2
 *
 * 后来：
 *      删除 lv1
 *      新建 lv3
 *
 * 如果仍然使用旧变量：
 *
 *      lv0_uuid    正确
 *      lv1_uuid   × 已失效
 *      lv2_uuid   × 已不是原来的卷
 *
 * 因此，本脚本属于【同步脚本】而不是【追加脚本】。
 *
 * 每次执行都会：
 *
 *  删除历史 UUID 变量
 * ② 获取当前最新卷列表
 * ③ 重新生成 UUID 变量
 *
 * 最终保证：
 *
 *      模块变量 == 当前系统真实卷
 *
 * 不会出现历史遗留 UUID。
 *
 * ==========================================================
 */


// ==========================================================
// 1、获取接口响应
// ==========================================================
const res = pm.response.json();


// ==========================================================
// 2、接口没有返回 data，结束脚本
// ==========================================================
if (!res.data) {
    console.log("响应 data 为空，停止生成模块变量。");
    return;
}


// ==========================================================
// 3、将 Object 转成数组
//
// data：
// {
//      uuid1:{}
//      uuid2:{}
//      uuid3:{}
// }
//
// 转换为：
// [
//      {},
//      {},
//      {}
// ]
//
// 并按照 sort 排序，保证 lv0、lv1、lv2 顺序固定。
// ==========================================================
const volumes = Object.values(res.data)
    .sort((a, b) => a.sort - b.sort);


// ==========================================================
// 4、清理历史模块变量
//
// 为什么？
//
// 防止卷删除后变量仍然存在。
//
// 例如：
//
// 上一次：
//
// lv0_uuid
// lv1_uuid
// lv2_uuid
//
// 本次：
//
// 只有两个卷。
//
// 如果不清理：
//
// lv2_uuid
//
// 仍然保存旧 UUID。
//
// 所以后续必须先删除历史变量。
// ==========================================================
for (let i = 0; i < 50; i++) {

    // 删除模块变量
    pm.moduleVariables.unset(`lv${i}_uuid`);
    pm.moduleVariables.unset(`lv${i}_filesystem`);

}


// ==========================================================
// 5、重新生成模块变量
//
// 使用 sort - 1 作为编号（sort 从 1 开始，变量从 lv0 开始）。
//
// 这样即使 sort 不连续（如 1、3、5），
// 变量名也能与实际卷一一对应：
//
// sort=1 → lv0_uuid
// sort=3 → lv2_uuid
// sort=5 → lv4_uuid
//
// 删除中间卷后不会出现错位。
// ==========================================================
volumes.forEach((volume) => {

    const sortIndex = volume.sort - 1;
    const uuidVar = `lv${sortIndex}_uuid`;
    const fsVar = `lv${sortIndex}_filesystem`;

    // 保存模块变量
    pm.moduleVariables.set(uuidVar, volume.uuid);
    pm.moduleVariables.set(fsVar, volume.filesystem);

    console.log(`${uuidVar} = ${volume.uuid}`);
    console.log(`${fsVar} = ${volume.filesystem}`);

});


// ==========================================================
// 6、保存卷数量
//
// 方便后续循环使用。
// ==========================================================
pm.moduleVariables.set("lv_count", volumes.length);


// ==========================================================
// 7、输出日志
// ==========================================================
console.log("====================================");
console.log(`共发现 ${volumes.length} 个卷`);
console.log("所有 UUID、filesystem 已同步到模块变量。");
console.log("====================================");
