/**
 * ==========================================================
 * 功能：同步磁盘设备名到模块变量
 * ==========================================================
 *
 * 【脚本目的】
 * 获取当前系统所有磁盘设备名，自动生成模块变量：
 *
 *      cap_disk0
 *      cap_disk1
 *      cap_disk2
 *      ...
 *
 * 后续接口可直接使用：
 *
 *      /v2/storage/CheckAvailablePool/{{cap_disk0}}
 *      /v2/storage/CheckAvailablePool/{{cap_disk1}}
 *      /v2/storage/CheckAvailablePool/{{cap_disk2}}
 *
 * 命名说明：
 *
 *      cap_ = CheckAvailablePool 接口专用前缀
 *
 * ==========================================================
 * 为什么每次都要同步？
 * ==========================================================
 *
 * 磁盘是动态变化的，例如：
 *
 * 第一次：
 *      sda
 *      sdb
 *      sdc
 *
 * 后来：
 *      拔掉 sdb
 *      插入 sdd
 *
 * 如果仍然使用旧变量：
 *
 *      cap_disk0  = sda   √
 *      cap_disk1  = sdb   × 已不存在
 *      cap_disk2  = sdc   × 序号已变
 *
 * 因此，本脚本属于【同步脚本】
 *
 * 每次执行：
 *
 * ① 删除历史磁盘变量
 * ② 获取当前最新磁盘列表
 * ③ 重新生成磁盘变量
 *
 * 保证：
 *
 *      模块变量 == 当前系统真实磁盘
 *
 * ==========================================================
 */


// ==========================================================
// 1、获取接口响应
// ==========================================================
const res = pm.response.json();


// ==========================================================
// 2、接口没有返回 data，结束脚本
// ==========================================================
if (!res.data) {

    console.log("响应 data 为空，停止生成磁盘变量。");

    return;
}


// ==========================================================
// 3、将 data 作为数组
//
// data:
//
// [
//      { "name": "HDD1",   "device": "/dev/sda"  },
//      { "name": "HDD2",   "device": "/dev/sdb"  },
//      { "name": "NVMe1",  "device": "/dev/sdza" }
// ]
//
// 提取 device 中 /dev/ 后面的部分作为磁盘名。
// 使用 trim() 去除可能存在的首尾空格，防止 URL 编码出现 %20。
// ==========================================================

const disks = res.data.map(d => d.device.replace(/^\/dev\//, '').trim());


// ==========================================================
// 4、清理历史模块变量
//
// 防止磁盘变化后变量残留。
//
// 例如：
//
// 上一次:
//
// cap_disk0
// cap_disk1
// cap_disk2
//
//
// 本次:
//
// 只有两个磁盘
//
//
// 如果不清理:
//
// cap_disk2
//
// 仍保存旧设备名
//
// ==========================================================

for (let i = 0; i < 50; i++) {

    pm.moduleVariables.unset(`cap_disk${i}`);

}


// ==========================================================
// 5、重新生成模块变量
//
// 生成:
//
// cap_disk0 = sda
// cap_disk1 = sdb
// cap_disk2 = sdc
// ...
//
// 用于接口:
//
// /v2/storage/CheckAvailablePool/{{cap_disk0}}
// /v2/storage/CheckAvailablePool/{{cap_disk1}}
// /v2/storage/CheckAvailablePool/{{cap_disk2}}
// ==========================================================

disks.forEach((disk, index) => {

    const variableName = `cap_disk${index}`;

    pm.moduleVariables.set(
        variableName,
        disk
    );

    console.log(
        `${variableName} = ${disk}`
    );

});


// ==========================================================
// 6、保存磁盘数量
//
// 方便后续接口循环使用。
// ==========================================================

pm.moduleVariables.set(
    "cap_disk_count",
    disks.length
);


// ==========================================================
// 7、输出日志
// ==========================================================

console.log("====================================");
console.log(`共发现 ${disks.length} 个磁盘`);
console.log("所有磁盘设备名已同步到模块变量。");
console.log("====================================");
