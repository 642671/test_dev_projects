/**
 * ==========================================================
 * 功能：同步存储池 UUID 到模块变量
 * ==========================================================
 *
 * 【脚本目的】
 * 获取当前系统所有存储池(UUID)，自动生成模块变量：
 *
 *      vg0_uuid
 *      vg1_uuid
 *      vg2_uuid
 *      ...
 *
 * 后续接口可直接使用：
 *
 *      vg0_uuid
 *      vg1_uuid
 *      vg2_uuid
 *
 * ==========================================================
 * 为什么每次都要同步？
 * ==========================================================
 *
 * 存储池是动态变化的，例如：
 *
 * 第一次：
 *      vg0
 *      vg1
 *      vg2
 *
 * 后来：
 *      删除vg1
 *      新建vg3
 *
 * 如果仍然使用旧变量：
 *
 *      vg0_uuid √
 *      vg1_uuid × 已失效
 *      vg2_uuid × 数据可能变化
 *
 * 因此，本脚本属于【同步脚本】
 *
 * 每次执行：
 *
 * ① 删除历史存储池UUID变量
 * ② 获取当前最新存储池列表
 * ③ 按sort排序
 * ④ 重新生成UUID变量
 *
 * 保证：
 *
 *      模块变量 == 当前系统真实存储池
 *
 * ==========================================================
 */


// ==========================================================
// 1、获取接口响应
// ==========================================================
const res = pm.response.json();


// ==========================================================
// 2、接口没有返回data，结束脚本
// ==========================================================
if (!res.data) {

    console.log("响应 data 为空，停止生成存储池变量。");

    return;
}


// ==========================================================
// 3、将Object转换为数组
//
// data:
//
// {
//      uuid1:{},
//      uuid2:{},
//      uuid3:{}
// }
//
// 转换为:
//
// [
//      {},
//      {},
//      {}
// ]
//
// 根据sort排序，保证vg0、vg1、vg2顺序固定。
// ==========================================================

const storagePools = Object.values(res.data)
    .sort((a, b) => a.sort - b.sort);


// ==========================================================
// 4、清理历史模块变量
//
// 防止存储池删除后变量残留。
//
// 例如：
//
// 上一次:
//
// vg0_uuid
// vg1_uuid
// vg2_uuid
//
//
// 本次:
//
// 只有两个存储池
//
//
// 如果不清理:
//
// vg2_uuid
//
// 仍保存旧UUID
//
// ==========================================================

for (let i = 0; i < 50; i++) {

    pm.moduleVariables.unset(`vg${i}_uuid`);

}


// ==========================================================
// 5、重新生成模块变量
//
// 使用 sort - 1 作为编号（sort 从 1 开始，变量从 vg0 开始）。
//
// 这样即使 sort 不连续（如 1、3、5），
// 变量名也能与实际存储池一一对应：
//
// sort=1 → vg0_uuid
// sort=3 → vg2_uuid
// sort=5 → vg4_uuid
//
// 删除中间存储池后不会出现错位。
// ==========================================================

storagePools.forEach((pool) => {

    const sortIndex = pool.sort - 1;
    const variableName = `vg${sortIndex}_uuid`;

    pm.moduleVariables.set(
        variableName,
        pool.uuid
    );

    console.log(
        `${variableName} = ${pool.uuid}`
    );

});


// ==========================================================
// 6、保存存储池数量
//
// 方便后续接口循环使用。
// ==========================================================

pm.moduleVariables.set(
    "vg_count",
    storagePools.length
);


// ==========================================================
// 7、输出日志
// ==========================================================

console.log("====================================");
console.log(`共发现 ${storagePools.length} 个存储池`);
console.log("所有存储池 UUID 已同步到模块变量。");
console.log("====================================");
